let currentLang = 'ru';

// Module registry
const registeredModules = {
  quiz: null,
  microscope: null,
  calculator: null,
  timeline: null,
  earth: null,
  uikit: null
};

export function getCurrentLang() {
  return currentLang;
}

export function registerModule(name, instance) {
  registeredModules[name] = instance;
}

export function registerQuiz(instance) {
  registeredModules.quiz = instance;
}

export function setLang(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  document.documentElement.lang = lang;
  
  applyTranslations();

  // Notify registered dynamic modules
  Object.entries(registeredModules).forEach(([name, mod]) => {
    if (mod && typeof mod.setLang === 'function') {
      try {
        mod.setLang(lang);
      } catch (e) {
        console.warn(`Error updating language in module ${name}:`, e);
      }
    }
  });
}

export function t(key) {
  return translations[currentLang]?.[key] ?? translations.ru[key] ?? key;
}

export function applyTranslations() {
  const dict = translations[currentLang] || translations.ru;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    const val = dict[key];
    if (val !== undefined) {
      el.textContent = val;
    }
  });

  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.dataset.i18nHtml;
    const val = dict[key];
    if (val !== undefined) {
      el.innerHTML = val;
    }
  });

  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.dataset.i18nTitle;
    const val = dict[key];
    if (val !== undefined) {
      el.title = val;
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    const val = dict[key];
    if (val !== undefined) {
      el.placeholder = val;
    }
  });
}
